#ifndef MOWKOW64_USER_LAYOUT64_H
#define MOWKOW64_USER_LAYOUT64_H

#include <memory64.h>

#define USER_PAGE_SIZE64 0x1000ULL
#define USER_IMAGE_BASE64 0x00400000ULL
#define USER_IMAGE_END64 0x00800000ULL
#define USER_HEAP_BASE64 0x100000000ULL
#define USER_HEAP_END64 0x100100000ULL
#define USER_STACK_GUARD64 0x1001ff000ULL
#define USER_STACK_BASE64 0x100200000ULL
#define USER_STACK_END64 0x100210000ULL
#define USER_STACK_GUARD_END64 0x100211000ULL
#define USER_SPACE_LIMIT64 4U

_Static_assert(USER_PAGE_SIZE64 == MEMMAN64_PAGE_SIZE, "user/allocator page size");
_Static_assert(((USER_IMAGE_BASE64 | USER_IMAGE_END64 | USER_HEAP_BASE64 |
	USER_HEAP_END64 | USER_STACK_GUARD64 | USER_STACK_BASE64 |
	USER_STACK_END64 | USER_STACK_GUARD_END64) & (USER_PAGE_SIZE64 - 1)) == 0,
	"user page alignment");
_Static_assert(USER_IMAGE_END64 - USER_IMAGE_BASE64 == 0x400000,
	"four MiB image window");
_Static_assert(USER_IMAGE_END64 <= MEMMAN64_EARLY_START &&
	MEMMAN64_EARLY_START < MEMMAN64_EARLY_END &&
	MEMMAN64_EARLY_END <= 0x40000000ULL, "backing in shared kernel RAM map");
_Static_assert(USER_IMAGE_BASE64 < USER_IMAGE_END64 &&
	USER_IMAGE_END64 <= USER_HEAP_BASE64 && USER_HEAP_BASE64 >= (1ULL << 32),
	"image/identity/heap separation");
_Static_assert(USER_HEAP_END64 - USER_HEAP_BASE64 == 0x100000 &&
	USER_STACK_END64 - USER_STACK_BASE64 == 0x10000, "heap and stack sizes");
_Static_assert(USER_HEAP_BASE64 < USER_HEAP_END64 &&
	USER_HEAP_END64 <= USER_STACK_GUARD64 &&
	USER_STACK_BASE64 - USER_STACK_GUARD64 == USER_PAGE_SIZE64 &&
	USER_STACK_BASE64 < USER_STACK_END64 &&
	USER_STACK_GUARD_END64 - USER_STACK_END64 == USER_PAGE_SIZE64 &&
	USER_STACK_GUARD_END64 < (1ULL << 39), "guards and canonical endpoints");

#endif
